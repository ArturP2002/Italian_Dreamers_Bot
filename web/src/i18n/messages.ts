export type MessageKey = keyof (typeof messages)["ru"];

export function t(language: Language, key: MessageKey): string {
  return messages[language][key];
}

export function tf(
  language: Language,
  key: MessageKey,
  vars: Record<string, string | number>,
): string {
  let text = t(language, key);
  for (const [k, v] of Object.entries(vars)) {
    text = text.replace(`{${k}}`, String(v));
  }
  return text;
}

export function greetingKey(date = new Date()): MessageKey {
  const hour = date.getHours();
  if (hour < 12) return "homeGreetingMorning";
  if (hour < 18) return "homeGreetingDay";
  return "homeGreetingEvening";
}
