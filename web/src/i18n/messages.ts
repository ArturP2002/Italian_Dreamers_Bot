export type Language = "ru" | "it";

// Telegram shares one web view storage between all accounts on a device,
// so the choice is keyed by Telegram user id.
function storageKey(): string {
  const user = window.Telegram?.WebApp?.initDataUnsafe?.user as { id?: number } | undefined;
  return user?.id ? `id_language_${user.id}` : "id_language";
}

export function loadLanguage(): Language | null {
  const value = localStorage.getItem(storageKey());
  if (value === "ru" || value === "it") return value;
  return null;
}

export function saveLanguage(language: Language): void {
  localStorage.setItem(storageKey(), language);
}

